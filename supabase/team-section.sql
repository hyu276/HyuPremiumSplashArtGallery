drop policy if exists "admins upload team files" on storage.objects;
create policy "admins upload team files"
on storage.objects for insert
to authenticated
with check (bucket_id = 'team' and (select public.is_admin()));

drop policy if exists "admins update team files" on storage.objects;
create policy "admins update team files"
on storage.objects for update
to authenticated
using (bucket_id = 'team' and (select public.is_admin()))
with check (bucket_id = 'team' and (select public.is_admin()));

drop policy if exists "admins delete team files" on storage.objects;
create policy "admins delete team files"
on storage.objects for delete
to authenticated
using (bucket_id = 'team' and (select public.is_admin()));
