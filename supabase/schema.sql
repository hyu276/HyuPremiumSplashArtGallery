-- Least-privilege Data API grants. RLS still decides which rows are accessible.
grant select on public.categories, public.image_credits, public.ranks, public.team_members to anon;
grant select on public.artworks to anon;
grant select, insert, update, delete on public.categories, public.image_credits, public.ranks, public.artworks, public.team_members to authenticated;
grant select on public.admins to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Public bucket for artwork images. Reads are public; writes remain protected by RLS.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'artworks',
  'artworks',
  true,
  10485760,
  array['image/jpeg','image/png','image/webp','image/gif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "admins upload artwork files" on storage.objects;
create policy "admins upload artwork files"
on storage.objects for insert
to authenticated
