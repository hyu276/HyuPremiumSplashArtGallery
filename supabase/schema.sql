create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.image_credits (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.ranks (
  id bigint generated by default as identity primary key,
  name text not null unique,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.artworks (
  id text primary key,
  name text not null,
  description text not null default '',
  category_id bigint not null references public.categories(id) on delete restrict,
  rank_id bigint not null references public.ranks(id) on delete restrict,
  credit_id bigint not null references public.image_credits(id) on delete restrict,
  image text not null,
  tags text[] not null default '{}',
  hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.team_members (
  id bigint generated by default as identity primary key,
  name text not null,
  image text not null,
  sort_order integer not null default 0,
  hidden boolean not null default false,
  facebook_url text not null default '',
  facebook_hidden boolean not null default false,
  tiktok_url text not null default '',
  tiktok_hidden boolean not null default false,
  instagram_url text not null default '',
  instagram_hidden boolean not null default false,
  x_url text not null default '',
  x_hidden boolean not null default false,
  linkedin_url text not null default '',
  linkedin_hidden boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists artworks_set_updated_at on public.artworks;
create trigger artworks_set_updated_at
before update on public.artworks
for each row execute function public.set_updated_at();

drop trigger if exists team_members_set_updated_at on public.team_members;
create trigger team_members_set_updated_at
before update on public.team_members
for each row execute function public.set_updated_at();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admins a
    where a.user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

